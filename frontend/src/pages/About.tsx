import { api } from '../api'
import { PageHead, useLoad } from '../ui'

type Eval = { available: boolean; generated_at?: string; mode?: string; cases?: number; overall?: any; by_check?: Record<string, any>; determinism?: boolean; citation_validity?: number }

export default function About() {
  const { data } = useLoad<Eval>(() => api('/eval'), [])
  return (
    <div className="max-w-[860px] space-y-8">
      <PageHead title="How Plumb works" sub="Brand governance treated as continuous integration: the policy is code, facts are data, people are the required reviewers, and every decision leaves a receipt." />
      <ol className="space-y-5">
        {[
          ['Guidelines become rules', 'A brand manager imports the guideline document. Plumb proposes typed rules (terminology, voice, claims, accessibility, channel rules), each quoting the sentence it came from. Rules are enforced only after a person approves them and publishes a policy version.'],
          ['Every draft gets checked', 'Rules run as code first: banned and preferred terms, pressure phrases, ALL-CAPS, link text, emoji, disclosure tags, channel limits. These are exact and repeat identically every time.'],
          ['Claims are verified, not guessed', 'Plumb pulls the claims out of the draft and finds the closest approved facts. Numbers, prices, percentages and lakh/crore counts are compared exactly. Everything else goes to a local DeBERTa NLI model. Only genuinely ambiguous cases go to an AI judge, and it can only cite facts it was shown. A fact past its end date makes the claim "expired" and points to its replacement.'],
          ['No citation, no finding', 'Every finding must cite a rule in the current policy version, and claims findings must cite a ledger fact. Anything a model produces without a valid citation is thrown away and counted.'],
          ['Fixes keep the writer’s message', 'Plumb reads the goal, audience and call to action first, and the creator confirms them. Each suggested fix is applied in a sandbox and the draft is re-checked. A fix is offered as verified only if the issue goes away, no new blocker appears, and the intent survives.'],
          ['People decide', 'Creators accept, edit or dispute each finding. Drafts with claims are routed to the claims reviewer as well as the brand manager. Overrides need a written reason. Approval locks the version and issues a signed audit receipt.'],
        ].map(([t, d], i) => (
          <li key={i} className="grid grid-cols-[28px_1fr] gap-3">
            <span className="mt-0.5 flex h-6 w-6 items-center justify-center rounded-full bg-ink text-xs font-bold text-white">{i + 1}</span>
            <div><h2 className="font-bold">{t}</h2><p className="text-ink-2">{d}</p></div>
          </li>
        ))}
      </ol>

      <section className="sheet p-5">
        <h2 className="font-bold">Measured reliability</h2>
        {!data?.available ? <p className="text-sm text-ink-2">The evaluation report is generated by CI from the golden set in the repository.</p> : (
          <div className="mt-2 space-y-3 text-sm">
            <p className="text-ink-2">Golden set of {data.cases} hand-labelled drafts for the demo brand, run in {data.mode}. Generated {data.generated_at && new Date(data.generated_at).toLocaleString()}.</p>
            <div className="grid gap-3 sm:grid-cols-4">
              <Stat label="Blocker precision" v={data.overall.block.precision} />
              <Stat label="Blocker recall" v={data.overall.block.recall} />
              <Stat label="All findings F1" v={data.overall.all.f1} />
              <Stat label="Valid citations" v={data.citation_validity ?? 1} />
            </div>
            <table className="w-full text-sm"><thead><tr className="border-b border-ink text-left text-xs text-mute"><th className="py-1">Check</th><th>Precision</th><th>Recall</th><th>Expected</th></tr></thead>
              <tbody className="divide-y divide-rule">{Object.entries(data.by_check || {}).map(([k, x]: any) => <tr key={k}><td className="py-1.5">{k}</td><td>{pct(x.precision)}</td><td>{pct(x.recall)}</td><td>{x.expected}</td></tr>)}</tbody></table>
            <p className="text-xs text-mute">Deterministic results identical across repeated runs: {data.determinism ? 'yes' : 'no'}. The golden set was written by the team, so these numbers are an upper bound; a blind external set is planned for Round 3.</p>
          </div>
        )}
      </section>
    </div>
  )
}

const pct = (x: number) => `${Math.round(x * 100)}%`
function Stat({ label, v }: { label: string; v: number }) {
  return <div className="rounded-lg bg-concrete/60 p-3"><p className="text-2xl font-bold tracking-[-0.02em]">{pct(v)}</p><p className="text-xs text-mute">{label}</p></div>
}
